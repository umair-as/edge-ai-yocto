        fail "no accelerator stack installed (composed: ${EDGE_ACCEL_COMPOSED:-unrecorded}) — the accelerator is baseline on every board, so this is a build or composition fault, not an image variant"
    fi
}

# ---------------- edge-checks/smoke/91-accel-drpai-v2l.sh ----------------

# DRP-AI (RZ/V2L): driver bound, render-group nodes, carveout, inference
# Quadlet ran when its /data payload is present.

edge_check accel.drpai-v2l cap:accel:drpai-v2l "Accelerator (drpai-v2l)" chk_accel_drpai

edge_cap_accel_drpai_v2l() { accel_is drpai-v2l; }

chk_accel_drpai() {
    local n l m memtotal_kb payload_present
    # render-group 0660 ownership (edge-drpai-udev) lets the rootless
    # container open the nodes via keep-groups; root:root 0600 breaks it.
    for n in drpai0 udmabuf0; do
        if [ -e "/dev/${n}" ]; then
            l=$(ls -l "/dev/${n}")
            if printf '%s' "${l}" | grep 'root render' >/dev/null; then
                pass "/dev/${n}: $(printf '%s' "${l}" | awk '{print $1, $3":"$4}')"
            else
                fail "/dev/${n} not root:render (rootless passthrough breaks): ${l}"
            fi
        else
            fail "/dev/${n} missing — module installed but driver did not bind"
        fi
    done

    for m in drpai u_dma_buf; do
        lsmod | grep "^${m} " >/dev/null && pass "module ${m} loaded" || fail "module ${m} not loaded"
    done

    # drp_reserved is a static 512 MB carveout on a 2 GB board.
    memtotal_kb=$(awk '/MemTotal/{print $2}' /proc/meminfo)
    if [ "${memtotal_kb}" -lt 1500000 ]; then
        pass "drp_reserved carveout in effect (MemTotal ${memtotal_kb} kB)"
    else
        warn "MemTotal ${memtotal_kb} kB — drp_reserved 512 MB carveout may not have applied"
    fi

    grep -q 'drpa mac_nmlint' /proc/interrupts \
        && pass "DRP-AI AI-MAC completion interrupt registered" \
        || warn "DRP-AI AI-MAC interrupt absent in /proc/interrupts"

    if sudo -n test -f /data/drpai/bin/drpai-tutorial-app 2>/dev/null; then
        payload_present=1
        pass "/data/drpai inference payload present"
    else
        payload_present=0
        warn "/data/drpai payload missing — fresh /data; place it to enable inference (Quadlet ConditionPathExists skips without it)"
    fi

    podman_wait_dropin

    # The Quadlet's ConditionPathExists skips cleanly without a payload; a
    # manual run also satisfies this.
    if sudo -n journalctl "_UID=${ECTR_UID}" -b --no-pager 2>/dev/null | grep -iE 'beagle|AI Processing Time' >/dev/null; then
        pass "DRP-AI inference ran this boot (result in user-${ECTR_UID} journal)"
    elif [ "${payload_present}" -eq 1 ]; then
        fail "DRP-AI inference did NOT run this boot despite payload present (Quadlet auto-start)"
    else
        info "DRP-AI inference not run — no /data/drpai payload (expected on fresh flash; not a defect)"
    fi
}

# ---------------- edge-checks/smoke/92-accel-dxm1.sh ----------------

# DEEPX DX-M1 (Raspberry Pi 5): PCIe endpoint, drivers, dxrtd and its IPC
# socket, rootless group access, inference Quadlet result.

edge_check accel.dxm1 cap:accel:dxm1 "Accelerator (dxm1)" chk_accel_dxm1

edge_cap_accel_dxm1() { accel_is dxm1; }

chk_accel_dxm1() {
    local dx_bdf ctl aspm m dx_pid dx_uid dx_user dx_status dx_unit dx_fps dx_result
    # PCIe endpoint, DEEPX vendor id 1ff4. The bridge is built in and the
    # driver autoloads from the modalias, so an absent endpoint means the
    # card, the slot or the link, not the image.
    if command -v lspci >/dev/null 2>&1; then
        dx_bdf=$(lspci -d 1ff4: -n 2>/dev/null | awk '{print $1; exit}')
        if [ -n "${dx_bdf}" ]; then
            pass "DX-M1 endpoint on PCIe at ${dx_bdf}"
            ctl=$(sudo -n lspci -vvs "${dx_bdf}" 2>/dev/null | grep -m1 -E '^\s*Control:')
            case "${ctl}" in
                *Mem+*BusMaster+*) pass "endpoint Control: Mem+ BusMaster+" ;;
                "") warn "lspci -vv needs sudo; endpoint control state not read" ;;
                *) fail "endpoint not enabled: ${ctl}" ;;
            esac
            aspm=$(sudo -n lspci -vvs "${dx_bdf}" 2>/dev/null | grep -m1 -oE 'ASPM (Disabled|L0s|L1|L0s L1)')
            [ -n "${aspm}" ] && info "link ${aspm}"
        else
            fail "no DEEPX (1ff4) PCIe endpoint enumerated — card not detected"
        fi
    else
        warn "lspci absent — PCIe endpoint not inspected"
    fi
    case "${EDGE_CMDLINE}" in
        *pcie_aspm=off*) pass "kernel cmdline: pcie_aspm=off (BCM2712 + DX-M1 SError guard)" ;;
        *) fail "kernel cmdline lacks pcie_aspm=off — link-state resets panic this board" ;;
    esac
    if sudo -n dmesg 2>/dev/null | grep -iE 'AER:.*(Uncorrect|Correct)ed error' >/dev/null; then
        warn "PCIe AER errors logged this boot (dmesg | grep AER)"
    else
        pass "no PCIe AER errors this boot"
    fi
    for m in dx_dma dxrt_driver; do
        lsmod | grep "^${m} " >/dev/null && pass "module ${m} loaded" || fail "module ${m} not loaded (udev modalias autoload after PCIe enumeration)"
    done
    devnode_mode /dev/dxrt0 'crw-rw----' dxrt 0660 "/dev/dxrt0 missing — dxrt_driver found no device"
    if systemctl is-active dxrtd.service >/dev/null 2>&1; then
        # BusyBox ps has no -C; read the main PID's uid from /proc instead.
        dx_pid=$(systemctl show -p MainPID --value dxrtd.service 2>/dev/null)
        dx_uid=$(awk '/^Uid:/{print $2}' "/proc/${dx_pid:-0}/status" 2>/dev/null)
        dx_user=$(getent passwd "${dx_uid:-}" 2>/dev/null | cut -d: -f1)
        [ "${dx_user}" = "dxrt" ] && pass "dxrtd active as dxrt" || fail "dxrtd active but running as '${dx_user:-?}' (uid ${dx_uid:-?}; expected dxrt)"
    else
        fail "dxrtd.service not active ($(systemctl is-active dxrtd.service 2>/dev/null)) — ConditionPathExistsGlob=/dev/dxrt* unmet, or the daemon failed"
    fi
    # edge-dxm1-runtime's dxrtd RuntimeDirectory override publishes the
    # dynamic-IPC socket at a fixed, bind-mountable path.
    if sudo -n test -S /run/dxrt/ipc.sock 2>/dev/null; then
        pass "dxrtd listening on /run/dxrt/ipc.sock"
    else
        fail "/run/dxrt/ipc.sock missing — dxrtd's RuntimeDirectory override did not take, or the daemon is down"
    fi
    if command -v dxrt-cli >/dev/null 2>&1; then
        # env explicitly: edge-dxrt-env.sh is profile.d-only and this image's
        # sudo PAM stack does not run pam_env.
        dx_status=$(sudo -n env DXRT_DYNAMIC_IPC_ENDPOINT=/run/dxrt/ipc.sock timeout 20 dxrt-cli -s 2>&1 | head -20)
        if printf '%s' "${dx_status}" | grep -iE 'device|firmware|fw' >/dev/null; then
            pass "dxrt-cli -s reports a device"
            printf '%s\n' "${dx_status}" | grep -iE 'device|firmware|fw|version' | head -4 | sed 's/^/        /'
        else
            warn "dxrt-cli -s gave no device report (daemon/firmware handshake): $(printf '%s' "${dx_status}" | head -1)"
        fi
    fi
    ectr_in_group dxrt
    if sudo -n test -f /data/dxm1/bin/run_model 2>/dev/null; then
        pass "/data/dxm1 inference payload present"
        dx_unit=$(ectr_unit_show dxm1-inference.service ActiveState Result ExecMainStatus ConditionResult NRestarts)
        dx_fps=$(sudo -n journalctl "_UID=${ECTR_UID}" -b --no-pager -t dxm1-inference 2>/dev/null | grep -E 'FPS *:' | tail -1 | sed 's/.*FPS *: *//')
        dx_result="ActiveState=$(unit_prop "${dx_unit}" ActiveState) Result=$(unit_prop "${dx_unit}" Result) ExecMainStatus=$(unit_prop "${dx_unit}" ExecMainStatus)"
        case "$(unit_state_class "${dx_unit}")" in
            unreadable) fail "cannot read dxm1-inference.service state (edge-ctr user manager not reachable)" ;;
            condition-unmet) fail "payload present but dxm1-inference.service did not start this boot (start condition unmet)" ;;
            completed)
                if [ -n "${dx_fps}" ]; then
                    pass "DX-M1 inference completed this boot (${dx_fps} FPS)"
                    [ "$(unit_prop "${dx_unit}" NRestarts)" -gt 0 ] 2>/dev/null \
                        && info "started after $(unit_prop "${dx_unit}" NRestarts) restart(s): dxrtd IPC was not ready on the first attempt"
                else
                    fail "dxm1-inference.service exited 0 without a benchmark result (${dx_result})"
                fi ;;
            running) warn "dxm1-inference.service still running or waiting for dxrtd (${dx_result})" ;;
            *) fail "dxm1-inference.service failed (${dx_result})" ;;
        esac
    else
        info "no /data/dxm1 payload — Quadlet skips (expected on a fresh flash; stage runtime libs + model + run_model there to enable)"
    fi
    podman_wait_dropin
}

# ---------------- edge-checks/smoke/93-accel-qnn-htp-v75.sh ----------------

# Hexagon NPU (VENTUNO Q): compute DSP up, FastRPC node and DMA-heap ACL for
# the fastrpc group, QAIRT platform validator, inference Quadlet result.

edge_check accel.qnn-htp-v75 cap:accel:qnn-htp-v75 "Accelerator (qnn-htp-v75)" chk_accel_qnn

edge_cap_accel_qnn_htp_v75() { accel_is qnn-htp-v75; }

chk_accel_qnn() {
    local r cdsp_state="" pv qn_unit qn_ms
    for r in /sys/class/remoteproc/remoteproc*; do
        [ "$(cat "${r}/name" 2>/dev/null)" = "cdsp" ] && cdsp_state=$(cat "${r}/state" 2>/dev/null)
    done
    [ "${cdsp_state}" = "running" ] \
        && pass "compute DSP (cdsp) remoteproc running" \
        || fail "cdsp remoteproc not running (state: ${cdsp_state:-absent})"
    # libcdsprpc opens the node read-only, so group read is enough.
    devnode_mode /dev/fastrpc-cdsp 'crw-r-----' fastrpc 0640 "/dev/fastrpc-cdsp missing — the fastrpc driver did not bind the compute DSP"
    if command -v getfacl >/dev/null 2>&1; then
        getfacl -p /dev/dma_heap/system 2>/dev/null | grep -x 'group:fastrpc:rw-' >/dev/null \
            && pass "/dev/dma_heap/system grants group fastrpc rw (ACL)" \
            || fail "/dev/dma_heap/system lacks the g:fastrpc ACL — the DSP cannot map buffers"
    else
        warn "getfacl absent — dma_heap ACL not inspected"
    fi
    ectr_in_group fastrpc
    # The DSP runs a calculator skel shipped with QAIRT: proves FastRPC, the
    # skel search path and the HTP v75 core with no model. Run as edge-ctr:
    # the login user is not in fastrpc and fails device creation by design.
    if command -v qnn-platform-validator >/dev/null 2>&1; then
        pv=$(sudo -n -u edge-ctr sh -c 'd=$(mktemp -d) && cd "$d" && timeout 60 qnn-platform-validator \
                 --backend dsp --testBackend --coreVersion --targetPath "$d"; rc=$?; cd / && rm -rf "$d"; exit $rc' \
                 2>&1 | tr -d '\r')
        if printf '%s' "${pv}" | grep -q 'Unit Test on the backend DSP: Passed'; then
            pass "qnn-platform-validator: DSP unit test passed ($(printf '%s' "${pv}" | sed -n 's/^Core Version of the backend DSP: //p'))"
        else
            fail "qnn-platform-validator DSP unit test did not pass: $(printf '%s' "${pv}" | grep -m1 -iE 'error|fail' )"
        fi
    else
        fail "qnn-platform-validator missing — qairt-sdk not installed"
    fi
    if sudo -n test -f /data/qnn-htp/model/model.bin 2>/dev/null; then
        pass "/data/qnn-htp inference payload present"
        qn_unit=$(ectr_unit_show qnn-htp-inference.service ActiveState Result ExecMainStatus ConditionResult)
        qn_ms=$(sudo -n journalctl "_UID=${ECTR_UID}" -b --no-pager -o cat SYSLOG_IDENTIFIER=systemd-qnn-htp-inference 2>/dev/null \
                    | sed -n 's/^ *NetRun: \([0-9]*\) us$/\1/p' | tail -1)
        case "$(unit_state_class "${qn_unit}")" in
            unreadable) fail "cannot read qnn-htp-inference.service state (edge-ctr user manager not reachable)" ;;
            condition-unmet) fail "payload present but qnn-htp-inference.service did not start this boot (start condition unmet)" ;;
            completed) pass "QNN HTP inference completed this boot (NetRun average ${qn_ms:-?} us)" ;;
            running) warn "qnn-htp-inference.service still running" ;;
            *) fail "qnn-htp-inference.service failed (ActiveState=$(unit_prop "${qn_unit}" ActiveState) Result=$(unit_prop "${qn_unit}" Result) ExecMainStatus=$(unit_prop "${qn_unit}" ExecMainStatus))" ;;
        esac
    else
        info "no /data/qnn-htp payload — Quadlet skips (expected on a fresh flash; stage model/model.bin + inputs there to enable)"
    fi
}

# ---------------- edge-checks/smoke/95-network.sh ----------------

# Networking: systemd-networkd owns DHCP on the uplink named by the shipped
# unit; unmanaged links are reserved for the kernel netboot path.

edge_check net.networkd core "Network (systemd-networkd)" chk_network

chk_network() {
    local links up_op i i_setup up_v4 up_v6 drv ns
    if systemctl is-active systemd-networkd.service >/dev/null 2>&1; then
        pass "systemd-networkd active"
    else
        fail "systemd-networkd inactive — no network manager running (NetworkManager was removed)"
    fi

    if command -v networkctl >/dev/null 2>&1; then
        links=$(networkctl --no-legend list 2>/dev/null)
        up_op=$(printf '%s\n' "${links}" | netlink_field "${EDGE_UPLINK}" 4)
        if [ "${up_op}" = "routable" ]; then
            pass "${EDGE_UPLINK} routable"
        elif [ -z "$(ip -o link show "${EDGE_UPLINK}" 2>/dev/null)" ]; then
            fail "uplink '${EDGE_UPLINK}' (from the shipped unit) does not exist — interface naming differs from the board include (links: $(ip -o link show | awk -F': ' '{print $2}' | grep -v '^lo$' | tr '\n' ' '))"
        else
            fail "${EDGE_UPLINK} not routable (operational='${up_op:-absent}') — DHCP uplink down"
        fi
        for i in ${EDGE_UNMANAGED}; do
            i_setup=$(printf '%s\n' "${links}" | netlink_field "${i}" 5)
            if [ "${i_setup}" = "unmanaged" ]; then
                pass "${i} unmanaged (as configured for netboot)"
            else
                info "${i} setup: ${i_setup:-absent}"
            fi
        done
    else
        warn "networkctl absent — cannot inspect link state"
    fi

    up_v4=$(ip -4 -o addr show "${EDGE_UPLINK}" 2>/dev/null | awk '{print $4}' | head -1)
    [ -n "${up_v4}" ] && pass "${EDGE_UPLINK} IPv4 ${up_v4}" || fail "${EDGE_UPLINK} has no IPv4 address (DHCP)"

    up_v6=$(ip -6 -o addr show "${EDGE_UPLINK}" scope global 2>/dev/null | awk '{print $4}' | head -1)
    [ -n "${up_v6}" ] && pass "${EDGE_UPLINK} IPv6 SLAAC ${up_v6}" \
        || warn "${EDGE_UPLINK} no global IPv6 (SLAAC) — if RA expected, drop net.ipv6.conf.all.accept_ra=0"

    # WiFi on boards that have it: the link exists with its driver bound;
    # association is operator provisioning, not an image property.
    if [ -e /sys/class/net/wlan0 ]; then
        drv=$(basename "$(readlink /sys/class/net/wlan0/device/driver 2>/dev/null)" 2>/dev/null)
        pass "wlan0 present (driver ${drv:-?}; not configured by the image)"
    elif [ "${EDGE_MACHINE}" = "raspberrypi5" ]; then
        fail "wlan0 absent on raspberrypi5 — brcmfmac/firmware/regulatory chain did not bring the radio up"
    fi

    # Without systemd-resolved, networkd must populate /etc/resolv.conf.
    ns=$(awk '/^nameserver /{print $2; exit}' /etc/resolv.conf 2>/dev/null)
    if [ -n "${ns}" ]; then
        pass "/etc/resolv.conf nameserver present (${ns})"
    else
        warn "/etc/resolv.conf has no nameserver — networkd-without-resolved wrote no DNS; name resolution fails (SSH-by-IP unaffected)"
    fi
}

