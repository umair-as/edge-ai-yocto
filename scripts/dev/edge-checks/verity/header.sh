#!/usr/bin/env bash
# On-device verified-boot check for the edge-ai distro: the boot chain's end
# state after a flash or OTA.
#
# Owns: the kernel cmdline from the signed slot payload (root=/dev/dm-0,
# dm-mod.create verity table, rauc.slot), the active dm-verity mapping and
# read-only root, verity events, the boot chain (U-Boot: slot FITs, FIT trust
# anchor, managed env; UEFI: systemd-boot entries and loader variables), RAUC
# slot state against the cmdline, module signing. edge-smoke-test.sh owns the
# running system (persistence, containers, security baseline, accelerator,
# network). Run both.
#
# Board-neutral: the boot chain and slots come from /etc/rauc/system.conf,
# slot devices from its device= entries (the by-rauc-slot udev links).
# Non-destructive: the only write attempted is a probe at / that must fail
# with EROFS.
#
#   ssh devel@<board-ip> 'bash -s' < scripts/dev/edge-verity-check.sh
#   or rsync + run as devel (sudo where root is required); --list prints the checks.
#
# On fresh media the baked U-Boot BOOTCOMMAND boots fitImage-A
# unconditionally; the managed env (BOOT_ORDER, counters, EDGE_VERITY_*)
# exists only after rauc-uboot-env-init.service has run once.
#
# Generated by scripts/dev/edge-checks/build.sh from lib.sh and verity/*.sh;
# edit those and regenerate (make check fails on a stale copy).

edge_suite_preamble() {
    info "MACHINE=${EDGE_MACHINE:-?} kernel $(uname -r) boot chain ${EDGE_BOOT_CHAIN}"
}
